USE hw_course;
CREATE TABLE IF NOT EXISTS course_team (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 course_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 role VARCHAR(16) NOT NULL, status VARCHAR(16) NOT NULL,
 created_at DATETIME(3) NOT NULL, updated_at DATETIME(3) NOT NULL,
 UNIQUE KEY uk_team_member(course_id,user_id), KEY idx_team_actor(user_id,status,course_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS course_team_state (
 id BIGINT UNSIGNED NOT NULL PRIMARY KEY, version INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS course_team_event (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 course_id BIGINT UNSIGNED NOT NULL, actor_id BIGINT UNSIGNED NOT NULL,
 target_id BIGINT UNSIGNED NOT NULL, action VARCHAR(24) NOT NULL,
 detail VARCHAR(1000) NOT NULL, created_at DATETIME(3) NOT NULL,
 KEY idx_team_event(course_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
